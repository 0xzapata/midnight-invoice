/**
 * Invoice names: the optional title a person gives an invoice (`invoiceName`,
 * e.g. "Brand refresh — Q4"), which is printed under the invoice number, and
 * the playful dashboard label ("Cosmic Phoenix 42") shown for invoices
 * without one, which must never appear on a client-facing document.
 *
 * Earlier versions stored a random label in `invoiceName` whenever the name
 * was left empty, so stored invoices (locally, on the server and on other
 * devices) can still carry one. Those are recognised by their exact shape
 * (one of the adjectives below, one of the nouns, a number 0–99). New invoices
 * never store a label: it is derived from the invoice id instead, so it is the
 * same on every device without being synced.
 */

const ADJECTIVES = ['Cosmic', 'Swift', 'Golden', 'Stellar', 'Bright', 'Noble', 'Grand', 'Prime', 'Royal', 'Epic'];
const NOUNS = ['Phoenix', 'Dragon', 'Thunder', 'Aurora', 'Nexus', 'Zenith', 'Summit', 'Pulse', 'Wave', 'Spark'];

const GENERATED_NAME = new RegExp(`^(?:${ADJECTIVES.join('|')}) (?:${NOUNS.join('|')}) (?:\\d|[1-9]\\d)$`);

/** True for a label generated by the app (now or by earlier versions), false for a name a person typed. */
export function isGeneratedInvoiceName(name: string | undefined | null): boolean {
  return typeof name === 'string' && GENERATED_NAME.test(name.trim());
}

/** The name to print on the invoice: the user's own name, or '' (nothing printed). */
export function printableInvoiceName(name: string | undefined | null): string {
  const trimmed = (name ?? '').trim();
  return isGeneratedInvoiceName(trimmed) ? '' : trimmed;
}

/** Stable label for an unnamed invoice, derived from its id (FNV-1a), e.g. "Golden Nexus 7". */
export function generatedInvoiceLabel(id: string): string {
  let hash = 0x811c9dc5;
  for (let i = 0; i < id.length; i++) {
    hash ^= id.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return `${ADJECTIVES[hash % 10]} ${NOUNS[Math.floor(hash / 10) % 10]} ${Math.floor(hash / 100) % 100}`;
}

/** What the dashboard calls an invoice: its name, a label stored by an earlier version, or one derived from its id. */
export function invoiceListLabel(invoice: { id: string; invoiceName?: string }): string {
  return invoice.invoiceName?.trim() || generatedInvoiceLabel(invoice.id);
}
