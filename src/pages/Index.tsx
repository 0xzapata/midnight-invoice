import { useState } from 'react';
import { useNavigate, useSearchParams } from 'react-router';
import { Plus, FileText, Settings, Sparkles, Paperclip, Save, Repeat } from 'lucide-react';
import { toast } from 'sonner';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Textarea } from '@/components/ui/textarea';
import { Label } from '@/components/ui/label';
import { InvoiceList } from '@/components/invoice/InvoiceList';
import { useInvoices } from '@/hooks/useInvoices';
import { useSettingsStore, DefaultSettings } from '@/stores/useSettingsStore';
import { CurrencySelector } from '@/components/ui/CurrencySelector';
import { Invoice } from '@/types/invoice';
import { Spinner } from '@/components/ui/spinner';
import { ThemeToggle } from '@/components/ThemeToggle';
import { env } from '@/env';
import { SyncStatusIndicator } from '@/components/sync/SyncStatusIndicator';
import { CloudSyncSettings } from '@/components/sync/CloudSyncSettings';
import { useCloudEnabled } from '@/stores/useCloudStore';
import { StatusFilterChips, TotalsStrip } from '@/components/invoice/status/StatusOverview';
import { useInvoiceStatusView, type StatusFilter } from '@/components/invoice/status/useInvoiceStatus';
import { NewFromTemplateButton } from '@/components/templates/NewFromTemplateButton';
import { HeaderNav } from '@/components/HeaderNav';
import { duplicateInvoiceData } from '@/lib/duplicateInvoice';

type Tab = 'invoices' | 'settings' | 'coming';
const TABS: readonly Tab[] = ['invoices', 'settings', 'coming'];

const Index = () => {
  const navigate = useNavigate();
  const { invoices, deleteInvoice, isLoading, saveDraft, getNextInvoiceNumber } = useInvoices();
  const [searchParams, setSearchParams] = useSearchParams();
  const tabParam = searchParams.get('tab') as Tab | null;
  // The tab lives in the URL (?tab=settings) so other screens can link to it.
  const activeTab: Tab = tabParam && TABS.includes(tabParam) ? tabParam : 'invoices';
  const { settings, updateSettings } = useSettingsStore();
  const cloudEnabled = useCloudEnabled();
  const [statusFilter, setStatusFilter] = useState<StatusFilter>('all');
  const statusView = useInvoiceStatusView(invoices, statusFilter);
  // Optional "Recurring" filter (invoices generated by a schedule), combined with the status filter.
  const [onlyRecurring, setOnlyRecurring] = useState(false);
  const recurringCount = invoices.filter((i) => i.recurringId).length;
  const showOnlyRecurring = onlyRecurring && recurringCount > 0;
  const listed = showOnlyRecurring ? statusView.filtered.filter((i) => i.recurringId) : statusView.filtered;

  // Local state for settings form to avoid auto-saving on every keystroke
  const [localSettings, setLocalSettings] = useState<DefaultSettings>(settings);
  const [shownTab, setShownTab] = useState<Tab>(activeTab);
  if (shownTab !== activeTab) {
    // Sync local state with the saved settings when switching to the settings tab
    setShownTab(activeTab);
    if (activeTab === 'settings') setLocalSettings(settings);
  }

  const selectTab = (tab: Tab) => {
    setSearchParams(tab === 'invoices' ? {} : { tab }, { replace: true });
  };

  const handleSaveSettings = () => {
    updateSettings(localSettings);
    toast.success('Settings saved successfully');
  };  // Zustand handles state synchronization automatically - no useEffect needed

  const handleViewInvoice = (invoice: Invoice) => {
    navigate(`/invoice/${invoice.id}`, { viewTransition: true });
  };

  const handleLoadSession = (invoice: Invoice) => {
    navigate(`/create/${invoice.id}`, { viewTransition: true });
  };

  const handleDuplicateInvoice = (invoice: Invoice) => {
    // The copy is opened in the editor as a draft under a new id (same as the invoice page's Duplicate).
    const newId = crypto.randomUUID();
    saveDraft(newId, duplicateInvoiceData(invoice, getNextInvoiceNumber));
    toast.success('Invoice duplicated');
    navigate(`/create/${newId}`, { viewTransition: true });
  };

  return (
    <div className="min-h-screen bg-background">
      {/* Development Mode Banner */}
      {env.VITE_APP_ENV === "DEVELOPMENT" && (
        <div className="w-full bg-primary/10 border-b border-primary/20 py-1.5 text-center">
          <span className="text-[11px] font-medium tracking-widest uppercase text-primary">
            Development Mode
          </span>
        </div>
      )}

      {/* Header */}
      <header className="sticky top-0 z-50 border-b border-border bg-background/95 backdrop-blur-sm supports-backdrop-filter:bg-background/60">
        <div className="container flex h-14 items-center justify-between gap-2">
            <div className="flex min-w-0 items-center gap-3">
              <div className="w-8 h-8 shrink-0 bg-primary/10 flex items-center justify-center">
                <img src="/favicon.svg" alt={`${env.VITE_APP_NAME} Logo`} className="w-4 h-4 text-primary" />
              </div>
              {/* On the narrowest phones the logo alone stands for the app name. */}
              <h1 className="truncate whitespace-nowrap text-sm font-semibold text-foreground max-[359px]:sr-only">{env.VITE_APP_NAME}</h1>
            </div>
          <div className="flex shrink-0 items-center gap-1 sm:gap-2">
            <SyncStatusIndicator />
            <HeaderNav />
            <Button size="sm" onClick={() => navigate('/create', { viewTransition: true })}>
              <Plus className="w-4 h-4 sm:mr-2" aria-hidden="true" />
              <span className="sr-only sm:not-sr-only">New Invoice</span>
            </Button>
          </div>
        </div>
      </header>

      {/* Main Content */}
      <main className="container py-8">
        <div className="max-w-3xl mx-auto">
          {/* Tabs */}
          {/* Tab icons and the "Coming Soon" label are dropped below sm so the row fits at 320 px. */}
          <div className="flex gap-3 sm:gap-4 mb-8 border-b border-border">
            <button
              onClick={() => selectTab('invoices')}
              className={`flex items-center gap-2 pb-3 px-1 text-sm font-medium border-b-2 transition-colors ${
                activeTab === 'invoices'
                  ? 'border-primary text-foreground'
                  : 'border-transparent text-muted-foreground hover:text-foreground'
              }`}
            >
              <FileText className="hidden w-4 h-4 sm:block" aria-hidden="true" />
              <span className="whitespace-nowrap"><span className="hidden sm:inline">Your </span>Invoices</span>
            </button>
            <button
              onClick={() => selectTab('settings')}
              className={`flex items-center gap-2 pb-3 px-1 text-sm font-medium border-b-2 transition-colors ${
                activeTab === 'settings'
                  ? 'border-primary text-foreground'
                  : 'border-transparent text-muted-foreground hover:text-foreground'
              }`}
            >
              <Settings className="hidden w-4 h-4 sm:block" aria-hidden="true" />
              Settings
            </button>
            <button
              onClick={() => selectTab('coming')}
              className={`flex items-center gap-2 pb-3 px-1 text-sm font-medium border-b-2 transition-colors ${
                activeTab === 'coming'
                  ? 'border-primary text-foreground'
                  : 'border-transparent text-muted-foreground hover:text-foreground'
              }`}
            >
              <Sparkles className="w-4 h-4" aria-hidden="true" />
              <span className="sr-only whitespace-nowrap sm:not-sr-only">Coming Soon</span>
            </button>
            <div className="ml-auto pb-1">
              <ThemeToggle />
            </div>
          </div>

          {activeTab === 'invoices' && (
            <>
              <div className="mb-8 flex flex-wrap items-start justify-between gap-x-4 gap-y-3">
                <div>
                <h2 className="text-2xl font-semibold text-foreground mb-2">Your Invoices</h2>
                <p className="text-sm text-muted-foreground">
                  {invoices.length === 0
                    ? 'Create professional invoices in seconds'
                    : `${invoices.length} invoice${invoices.length === 1 ? '' : 's'} ${cloudEnabled ? 'synced to your cloud workspace' : 'saved locally'}`}
                </p>
                </div>
                <NewFromTemplateButton />
              </div>

              {isLoading ? (
                <div className="flex items-center justify-center py-16">
                  <Spinner size="lg" />
                </div>
              ) : (
                <>
                {invoices.length > 0 && (
                  <>
                    <TotalsStrip summary={statusView.summary} onSelect={setStatusFilter} className="mb-4" />
                    <div className="mb-4 flex flex-wrap items-start gap-2">
                      <StatusFilterChips value={statusFilter} counts={statusView.counts} onChange={setStatusFilter} />
                      {recurringCount > 0 && (
                        <button
                          type="button"
                          aria-pressed={showOnlyRecurring}
                          onClick={() => setOnlyRecurring((v) => !v)}
                          className={`inline-flex h-8 items-center gap-1.5 border px-2.5 text-xs font-medium transition-colors focus-visible:outline-hidden focus-visible:ring-2 focus-visible:ring-ring ${
                            showOnlyRecurring ? 'border-primary bg-primary/10 text-primary' : 'border-border text-muted-foreground hover:bg-accent hover:text-foreground'
                          }`}
                        >
                          <Repeat className="h-3.5 w-3.5" aria-hidden="true" />
                          Recurring{' '}
                          <span className="font-mono tabular-nums opacity-80">
                            {recurringCount}
                            <span className="sr-only"> invoices</span>
                          </span>
                        </button>
                      )}
                    </div>
                  </>
                )}
                {invoices.length > 0 && listed.length === 0 ? (
                  <div className="border border-dashed border-border py-12 text-center text-sm text-muted-foreground">
                    No {statusFilter === 'all' ? '' : `${statusFilter} `}{showOnlyRecurring ? 'recurring ' : ''}invoices.{' '}
                    <button
                      type="button"
                      className="text-primary underline-offset-4 hover:underline"
                      onClick={() => {
                        setStatusFilter('all');
                        setOnlyRecurring(false);
                      }}
                    >
                      Show all
                    </button>
                  </div>
                ) : (
                <InvoiceList
                  invoices={listed}
                  onView={handleViewInvoice}
                  onLoadSession={handleLoadSession}
                  onDuplicate={handleDuplicateInvoice}
                  onDelete={deleteInvoice}
                />
                )}
                </>
              )}

              {invoices.length === 0 && !isLoading && (
                <div className="mt-8 flex justify-center">
                  <Button size="lg" onClick={() => navigate('/create', { viewTransition: true })} className="h-12 px-8">
                    <Plus className="w-5 h-5 mr-2" />
                    Create Your First Invoice
                  </Button>
                </div>
              )}
            </>
          )}

          {activeTab === 'settings' && (
            <>
              <div className="mb-8">
                <h2 className="text-2xl font-semibold text-foreground mb-2">Settings</h2>
                <p className="text-sm text-muted-foreground">
                  Configure default values for new invoices. These can be applied using the "Use Defaults" button.
                </p>
              </div>

              <div className="space-y-6 max-w-lg">
                <div className="space-y-2">
                  <Label htmlFor="defaultFromName" className="text-xs text-muted-foreground">
                    Default Name / Company
                  </Label>
                  <Input
                    id="defaultFromName"
                    placeholder="Your name or company"
                    value={localSettings.fromName}
                    onChange={(e) => setLocalSettings(prev => ({ ...prev, fromName: e.target.value }))}
                    className="bg-secondary border-border"
                  />
                </div>

                <div className="space-y-2">
                  <Label htmlFor="defaultFromEmail" className="text-xs text-muted-foreground">
                    Default Email
                  </Label>
                  <Input
                    id="defaultFromEmail"
                    type="email"
                    placeholder="your@email.com"
                    value={localSettings.fromEmail}
                    onChange={(e) => setLocalSettings(prev => ({ ...prev, fromEmail: e.target.value }))}
                    className="bg-secondary border-border"
                  />
                </div>

                <div className="space-y-2">
                  <Label htmlFor="defaultFromAddress" className="text-xs text-muted-foreground">
                    Default Address
                  </Label>
                  <Textarea
                    id="defaultFromAddress"
                    placeholder="Street, City, Country"
                    rows={2}
                    value={localSettings.fromAddress}
                    onChange={(e) => setLocalSettings(prev => ({ ...prev, fromAddress: e.target.value }))}
                    className="bg-secondary border-border resize-none"
                  />
                </div>

                <div className="space-y-2">
                  <Label htmlFor="defaultPaymentDetails" className="text-xs text-muted-foreground">
                    Default Payment Details
                  </Label>
                  <Textarea
                    id="defaultPaymentDetails"
                    placeholder="Bank name, account number, etc."
                    rows={3}
                    value={localSettings.paymentDetails}
                    onChange={(e) => setLocalSettings(prev => ({ ...prev, paymentDetails: e.target.value }))}
                    className="bg-secondary border-border resize-none text-sm"
                  />
                </div>

                <div className="grid grid-cols-2 gap-4">
                  <div className="space-y-2">
                    <Label htmlFor="defaultTaxRate" className="text-xs text-muted-foreground">
                      Default Tax Rate (%)
                    </Label>
                    <Input
                      id="defaultTaxRate"
                      type="number"
                      min="0"
                      step="0.01"
                      placeholder="0"
                      value={localSettings.taxRate || ''}
                      onChange={(e) => setLocalSettings(prev => ({ ...prev, taxRate: parseFloat(e.target.value) || 0 }))}
                      className="bg-secondary border-border"
                    />
                  </div>
                  
                  <div className="space-y-2">
                    <Label className="text-xs text-muted-foreground">
                      Default Currency
                    </Label>
                    <CurrencySelector
                      value={localSettings.currency}
                      onChange={(value) => setLocalSettings(prev => ({ ...prev, currency: value }))}
                    />
                  </div>
                </div>

                <div className="space-y-2">
                  <Label htmlFor="defaultNotes" className="text-xs text-muted-foreground">
                    Default Notes
                  </Label>
                  <Textarea
                    id="defaultNotes"
                    placeholder="Thank you for your business!"
                    rows={3}
                    value={localSettings.notes}
                    onChange={(e) => setLocalSettings(prev => ({ ...prev, notes: e.target.value }))}
                    className="bg-secondary border-border resize-none text-sm"
                  />
                </div>

                <div className="pt-4">
                  <Button onClick={handleSaveSettings}>
                    <Save className="w-4 h-4 mr-2" />
                    Save Settings
                  </Button>
                </div>
              </div>

              <div className="mt-12 border-t border-border pt-8">
                <CloudSyncSettings />
              </div>
            </>
          )}

          {activeTab === 'coming' && (
            <>
              <div className="mb-8">
                <h2 className="text-2xl font-semibold text-foreground mb-2">Coming Soon</h2>
                <p className="text-sm text-muted-foreground">
                  Exciting features we're working on for future updates.
                </p>
              </div>

              <div className="space-y-4">
                <div className="flex items-center gap-4 p-4 rounded-lg border border-border bg-card">
                  <div className="w-10 h-10 rounded-md bg-yellow-500/10 flex items-center justify-center">
                    <Paperclip className="w-5 h-5 text-yellow-500" />
                  </div>
                  <div>
                    <p className="font-medium text-foreground">File Attachments</p>
                    <p className="text-sm text-muted-foreground">Add logos and documents to invoices</p>
                  </div>
                </div>
              </div>
            </>
          )}
        </div>
      </main>
    </div>
  );
};

export default Index;