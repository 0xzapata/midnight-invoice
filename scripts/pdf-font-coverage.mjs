#!/usr/bin/env node
/**
 * Regenerates the glyph-coverage tables used to pick PDF fallback fonts:
 * - src/components/invoice/pdfFontCoverage.ts: code-point ranges of Noto Sans
 *   Mono (the invoice font), bundled so the app can tell, without any
 *   download, whether an invoice needs a fallback face at all;
 * - public/fonts/fallback/coverage.json: the ranges of each fallback face,
 *   fetched (browser) or read from static assets (Worker) only when needed.
 *
 * Run after adding or replacing a font: `node scripts/pdf-font-coverage.mjs`.
 * server/pdf-fonts.test.ts fails when these tables drift from the font files.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import * as fontkit from 'fontkit';
import faceList from '../src/components/invoice/pdfFallbackFaces.json' with { type: 'json' };

const { PDF_FALLBACK_FACES } = faceList;

const root = path.resolve(import.meta.dirname, '..');

/** Sorted, merged [start, end] ranges of the code points a font maps to a glyph. */
export function coverage(file) {
  const font = fontkit.create(readFileSync(path.join(root, 'public', file)));
  const points = [...font.characterSet].filter((cp) => font.glyphForCodePoint(cp).id !== 0).sort((a, b) => a - b);
  const ranges = [];
  for (const cp of points) {
    const last = ranges.at(-1);
    if (last && cp === last[1] + 1) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  return ranges;
}

const mono = coverage('/fonts/NotoSansMono-Regular.ttf');
writeFileSync(
  path.join(root, 'src/components/invoice/pdfFontCoverage.ts'),
  `// Generated by scripts/pdf-font-coverage.mjs from public/fonts/NotoSansMono-Regular.ttf. Do not edit.\n` +
    `/** Code points with a glyph in Noto Sans Mono, as sorted inclusive [start, end] ranges. */\n` +
    `export const NOTO_SANS_MONO_COVERAGE: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(mono)};\n`,
);

const faces = PDF_FALLBACK_FACES.map((face) => ({ family: face.family, ranges: coverage(face.src) }));
writeFileSync(path.join(root, 'public/fonts/fallback/coverage.json'), `${JSON.stringify({ faces })}\n`);
console.log(`Noto Sans Mono: ${mono.length} ranges; fallback faces: ${faces.map((f) => `${f.family} ${f.ranges.length}`).join(', ')}`);
